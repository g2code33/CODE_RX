export type DeliverySourceKind =
  | 'rich_text'
  | 'plain_text'
  | 'attachment_pdf'
  | 'attachment_png'
  | 'attachment_text'
  | 'attachment_office'
  | 'unsupported';

export type DeliveryKind = 'generated_pdf' | 'stamped_pdf' | 'stamped_png' | 'converted_pdf';

export interface DeliveryPlan {
  /** True when a stamped client copy can be produced right now. */
  available: boolean;
  kind: DeliveryKind | null;
  sourceKind: DeliverySourceKind;
  /** Short label for the portal and the Phantom panel. */
  label: string;
  contentType: string;
  extension: string;
  /** Client-safe explanation when nothing can be delivered. */
  message: string;
  /** Machine reason for the audit log (never shown to the client). */
  reason: string | null;
}

