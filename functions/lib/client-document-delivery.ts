interface RawBlock {
  type?: string;
  content?: unknown;
  level?: unknown;
  items?: unknown;
  language?: unknown;
  rows?: unknown;
  caption?: unknown;
  fileKey?: unknown;
  attachmentId?: unknown;
  url?: unknown;
}

interface ParsedSnapshot {
  blocks: ContentBlock[];
  /** File references the blocks carry, so the caller can fetch and embed them. */
  attachments: Array<{ fileKey: string; caption: string; type: 'image' | 'file' }>;
  /** True when the only content is a single attachment reference. */
  singleAttachmentOnly: boolean;
}

const asText = (value: unknown): string => {
  if (typeof value === 'string') return value;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return value.map(asText).filter(Boolean).join(' ');
  if (value && typeof value === 'object') {
    const record = value as Record<string, unknown>;
    return asText(record.text ?? record.content ?? record.value ?? '');
  }
  return '';
};

const stripHtml = (value: string): string =>
  value
    .replace(/<\s*(script|style)[\s\S]*?<\/\s*\1\s*>/gi, ' ')
    .replace(/<\s*br\s*\/?>/gi, '\n')
    .replace(/<\/\s*(p|div|li|h[1-6]|tr)\s*>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/\n{3,}/g, '\n\n');

const ensureSentence = (value: string): string => value.replace(/^\s+|\s+$/g, '');

/**
 * Markdown-lite → blocks. Enough for the plain-text snapshots the Phantom route
 * can store (`contentText`) and for text files delivered as stamped PDFs.
 */
export const textToBlocks = (value: string): ContentBlock[] => {
  const blocks: ContentBlock[] = [];
  const lines = value.replace(/\r\n?/g, '\n').split('\n');
  let paragraph: string[] = [];
  let list: { items: string[]; ordered: boolean } | null = null;
  let code: { lines: string[]; language?: string } | null = null;
  let quote: string[] = [];

  const flushParagraph = () => {
    const text = ensureSentence(paragraph.join(' '));
    if (text) blocks.push({ type: 'paragraph', text });
    paragraph = [];
  };
  const flushList = () => {
    if (list && list.items.length) blocks.push({ type: 'list', items: list.items, ordered: list.ordered });
    list = null;
  };
  const flushQuote = () => {
    const text = ensureSentence(quote.join(' '));
    if (text) blocks.push({ type: 'quote', text });
    quote = [];
  };
  const flushAll = () => { flushParagraph(); flushList(); flushQuote(); };

  for (const rawLine of lines) {
    const line = rawLine.replace(/\s+$/, '');
    const fence = /^\s*```(\w*)\s*$/.exec(line);
    if (fence) {
      if (code) {
        blocks.push({ type: 'code', text: code.lines.join('\n'), language: code.language });
        code = null;
      } else {
        flushAll();
        code = { lines: [], language: fence[1] || undefined };
      }
      continue;
    }
    if (code) {
      code.lines.push(rawLine);
      continue;
    }
    if (!line.trim()) {
      flushAll();
      continue;
    }
    const heading = /^(#{1,4})\s+(.*)$/.exec(line);
    if (heading) {
      flushAll();
      blocks.push({ type: 'heading', text: heading[2], level: heading[1].length });
      continue;
    }
    if (/^\s*([-*_])\s*\1\s*\1[\s\-*_]*$/.test(line.replace(/\s/g, '')) || /^-{3,}$/.test(line.trim())) {
      flushAll();
      blocks.push({ type: 'divider' });
      continue;
    }
    const bullet = /^\s*[-*+]\s+(.*)$/.exec(line);
    const numbered = /^\s*\d+[.)]\s+(.*)$/.exec(line);
    if (bullet || numbered) {
      flushParagraph();
      flushQuote();
      const ordered = !!numbered;
      if (!list || list.ordered !== ordered) {
        flushList();
        list = { items: [], ordered };
      }
      list.items.push((bullet ? bullet[1] : numbered![1]).replace(/\*\*(.*?)\*\*/g, '$1'));
      continue;
    }
    if (/^\s*>\s?/.test(line)) {
      flushParagraph();
      flushList();
      quote.push(line.replace(/^\s*>\s?/, ''));
      continue;
    }
    paragraph.push(line.replace(/\*\*(.*?)\*\*/g, '$1'));
  }
  if (code) blocks.push({ type: 'code', text: code.lines.join('\n'), language: code.language });
  flushAll();
  return blocks;
};

/**
 * Normalises whatever the snapshot holds into the renderer's block model.
 * Rich text is stored as the Vault block list, so the mapping keeps headings,
 * lists, tables, callouts and code — the structure of a Code Rx document.
 */
export const parseSnapshot = (snapshot: string, format: string | null): ParsedSnapshot => {
  const attachments: ParsedSnapshot['attachments'] = [];
  const normalized = (format || 'blocks').toLowerCase();
  let raw: unknown = null;
  if (normalized === 'blocks' || normalized === 'json') {
    try {
      raw = JSON.parse(snapshot);
    } catch {
      raw = null;
    }
  }

  if (raw && typeof raw === 'object' && !Array.isArray(raw) && Array.isArray((raw as { blocks?: unknown }).blocks)) {
    raw = (raw as { blocks: unknown[] }).blocks;
  }

  const blocks: ContentBlock[] = [];
  if (Array.isArray(raw)) {
    for (const entry of raw as RawBlock[]) {
      const type = String(entry?.type || 'paragraph');
      const content = asText(entry?.content);
      switch (type) {
        case 'heading':
          blocks.push({ type: 'heading', text: content, level: Math.max(1, Math.min(4, Number(entry?.level) || 1)) });
          break;
        case 'paragraph':
          if (content.trim()) blocks.push({ type: 'paragraph', text: content });
          break;
        case 'bulletList':
        case 'numberedList': {
          const items = Array.isArray(entry?.items) ? (entry!.items as unknown[]).map(asText).filter(Boolean) : [];
          if (items.length) blocks.push({ type: 'list', items, ordered: type === 'numberedList' });
          break;
        }
        case 'checklist': {
          const items = Array.isArray(entry?.items)
            ? (entry!.items as unknown[]).map((item) => {
              const record = (item || {}) as Record<string, unknown>;
              return `${record.checked || record.done ? '[x]' : '[ ]'} ${asText(record.text ?? record.label ?? item)}`.trim();
            }).filter((item) => item.length > 3)
            : [];
          if (items.length) blocks.push({ type: 'list', items, ordered: false });
          break;
        }
        case 'quote':
          if (content.trim()) blocks.push({ type: 'quote', text: content });
          break;
        case 'callout':
          if (content.trim()) blocks.push({ type: 'callout', text: content, variant: String((entry as { variant?: unknown })?.variant || '') });
          break;
        case 'code':
          blocks.push({ type: 'code', text: content || String((entry as { code?: unknown })?.code || ''), language: String(entry?.language || '') });
          break;
        case 'divider':
          blocks.push({ type: 'divider' });
          break;
        case 'table': {
          const rows = Array.isArray(entry?.rows)
            ? (entry!.rows as unknown[]).map((row) => (Array.isArray(row) ? row.map(asText) : [asText(row)]))
            : [];
          if (rows.length) blocks.push({ type: 'table', rows });
          break;
        }
        case 'image':
        case 'file':
        case 'embed': {
          const fileKey = typeof entry?.fileKey === 'string' ? entry.fileKey : '';
          const caption = asText(entry?.caption) || asText(entry?.content) || (type === 'image' ? 'Figure' : 'Attachment');
          if (fileKey) {
            attachments.push({ fileKey, caption, type: type === 'image' ? 'image' : 'file' });
            blocks.push(type === 'image'
              ? { type: 'image', caption }
              : { type: 'file', caption });
          } else if (content.trim()) {
            blocks.push({ type: 'paragraph', text: content });
          }
          break;
        }
        case 'formula':
          if (content.trim()) blocks.push({ type: 'code', text: content });
          break;
        default:
          if (content.trim()) blocks.push({ type: 'paragraph', text: content });
          break;
      }
    }
  }

  if (!blocks.length) {
    const source = normalized === 'html' ? stripHtml(snapshot) : snapshot;
    blocks.push(...textToBlocks(source));
  }

  const textual = blocks.filter((block) => block.type !== 'image' && block.type !== 'file');
  const singleAttachmentOnly = textual.length === 0 && attachments.length === 1;

  return { blocks, attachments, singleAttachmentOnly };
};

