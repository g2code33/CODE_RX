/**
 * CODE Rx SOCIETY — client document delivery service (Phase 8).
 *
 * This module is the only place that decides *what bytes a client may receive*.
 * It never returns a source file: every delivery path renders a stamped
 * representation through `functions/lib/client-delivery(-pdf)`, and every
 * failure becomes a controlled refusal with a client-safe message.
 *
 * The plan is derived from what the document already stores — the
 * `content_snapshot` (rich text blocks or plain text) produced by the Phantom
 * document route, plus any Vault attachment its blocks reference. Nothing new is
 * persisted except the cache key in the existing `storage_reference` column.
 */

