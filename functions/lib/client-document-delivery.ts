export interface RenderedDelivery {
  bytes: Uint8Array;
  contentType: string;
  extension: string;
  kind: DeliveryKind;
  /** sha256 of the delivered bytes — recorded in the audit log. */
  sha256: string;
  /** sha256 of the source material the artifact was rendered from. */
  sourceFingerprint: string;
}

export class DeliveryRefusal extends Error {
  readonly reason: string;
  readonly plan: DeliveryPlan;
  constructor(reason: string, message: string, plan: DeliveryPlan) {
    super(message);
    this.name = 'DeliveryRefusal';
    this.reason = reason;
    this.plan = plan;
  }
}

export interface RenderInput extends DeliveryInput {
  /** Raw bytes of the primary attachment, when the plan needs them. */
  attachmentBytes?: Uint8Array | null;
  /** Bytes of the images the rich-text blocks reference, keyed by fileKey. */
  embeddedImages?: Record<string, Uint8Array | null>;
}

export const sourceFingerprint = async (input: RenderInput): Promise<string> => {
  const parts = [
    input.document.reference,
    input.document.version,
    input.document.contentSnapshot || '',
    input.attachment?.fileKey || '',
    String(input.attachment?.sizeBytes ?? ''),
    JSON.stringify(input.meta?.customization || {}),
  ];
  return (await sha256Hex(parts.join('\u0000'))).slice(0, 16);
};

const metaFor = (meta: DeliveryMeta) => ({
  projectName: meta.projectName,
  projectReference: meta.projectReference,
  documentTitle: meta.documentTitle,
  documentReference: meta.documentReference,
  version: meta.version,
  clientName: meta.clientName,
  category: meta.category,
  issuedAt: meta.issuedAt,
  customization: meta.customization || null,
});

/**
 * Renders the stamped client copy. Every branch either produces a stamped
 * artifact or throws `DeliveryRefusal`; none of them returns source bytes.
 */
export const renderClientDelivery = async (input: RenderInput): Promise<RenderedDelivery> => {
  const plan = planClientDelivery(input);
  if (!plan.available || !plan.kind) {
    throw new DeliveryRefusal(plan.reason || 'delivery_unavailable', plan.message, plan);
  }
  const logo = await getBrandMark();
  const fingerprint = await sourceFingerprint(input);
  const attempt = async (): Promise<Uint8Array> => {
    if (input.meta?.customization?.rawDocumentDelivery) {
      if (input.attachmentBytes && input.attachmentBytes.length) {
        return input.attachmentBytes;
      }
    }
    switch (plan.sourceKind) {
      case 'attachment_pdf': {
        const bytes = input.attachmentBytes;
        if (!bytes || !bytes.length) throw new DeliveryRefusal('attachment_unavailable', plan.message, plan);
        const result = await stampPdfSource(bytes, metaFor(input.meta), logo);
        if (!result.ok) {
          throw new DeliveryRefusal(result.error.reason, UNSUPPORTED_MESSAGE, plan);
        }
        return result.bytes;
      }
      case 'attachment_png': {
        const bytes = input.attachmentBytes;
        if (!bytes || !bytes.length) throw new DeliveryRefusal('attachment_unavailable', plan.message, plan);
        if (!isPng(bytes)) throw new DeliveryRefusal('not_png', UNSUPPORTED_MESSAGE, plan);
        const image = await decodePng(bytes);
        return buildStampedImage({ meta: input.meta, image, logo });
      }
      case 'attachment_office': {
        const bytes = input.attachmentBytes;
        if (!bytes || !bytes.length) throw new DeliveryRefusal('attachment_unavailable', plan.message, plan);
        const converted = await convertOfficeDocument(bytes, input.attachment?.mimeType || null);
        if (!converted) throw new DeliveryRefusal('office_conversion_unsupported', UNSUPPORTED_MESSAGE, plan);
        const blocks = [...textToBlocks(converted.text)];
        if (converted.notes.length) {
          blocks.push({ type: 'divider' });
          blocks.push({ type: 'list', items: converted.notes, ordered: false });
        }
        return buildBrandedPdf({ meta: metaFor(input.meta), blocks, logo });
      }
      case 'attachment_text': {
        const bytes = input.attachmentBytes;
        if (!bytes || !bytes.length) throw new DeliveryRefusal('attachment_unavailable', plan.message, plan);
        const text = new TextDecoder('utf-8', { fatal: false }).decode(bytes);
        const blocks = textToBlocks(text);
        return buildBrandedPdf({ meta: metaFor(input.meta), blocks, logo });
      }
      default: {
        const parsed = parseSnapshot(input.document.contentSnapshot || '', input.document.contentSnapshotFormat);
        const blocks = await attachImages(parsed.blocks, parsed.attachments, input.embeddedImages || {});
        return buildBrandedPdf({ meta: metaFor(input.meta), blocks, logo });
      }
    }
  };

  let bytes: Uint8Array;
  try {
    bytes = await attempt();
  } catch (error) {
    if (error instanceof DeliveryRefusal) throw error;
    const reason = error instanceof DeliveryError ? error.reason : 'delivery_render_failed';
    // Fail closed: a renderer problem must never degrade into a passthrough.
    throw new DeliveryRefusal(reason, UNSUPPORTED_MESSAGE, plan);
  }
  if (!bytes.length) throw new DeliveryRefusal('empty_artifact', UNSUPPORTED_MESSAGE, plan);

  return {
    bytes,
    contentType: plan.contentType,
    extension: plan.extension,
    kind: plan.kind,
    sha256: await sha256Hex(bytes),
    sourceFingerprint: fingerprint,
  };
};

/** Decodes and embeds the images a rich-text document references. */
const attachImages = async (
  blocks: ContentBlock[],
  attachments: ParsedSnapshot['attachments'],
  embedded: Record<string, Uint8Array | null>,
): Promise<ContentBlock[]> => {
  const decoded = new Map<string, DecodedImage>();
  for (const attachment of attachments) {
    if (attachment.type !== 'image') continue;
    const bytes = embedded[attachment.fileKey];
    if (!bytes || !isPng(bytes)) continue;
    try {
      decoded.set(attachment.fileKey, await decodePng(bytes));
    } catch {
      // An image the engine cannot decode is omitted with a note — the source
      // bytes are never bundled into the artifact.
    }
  }
  let index = 0;
  return blocks.map((block) => {
    if (block.type === 'image') {
      const attachment = attachments[index];
      index += 1;
      const image = attachment ? decoded.get(attachment.fileKey) : undefined;
      return { type: 'image', caption: block.caption, image: image || null };
    }
    return block;
  });
};

// ---------------------------------------------------------------------------
// Artifact cache (R2, under the client-exports/ prefix only)
// ---------------------------------------------------------------------------

export const CLIENT_ARTIFACT_PREFIX = 'client-exports/';

export const artifactKey = (
  clientPublicId: string,
  documentPublicId: string,
  extension: string,
  fingerprint: string,
): string =>
  `${CLIENT_ARTIFACT_PREFIX}${clientPublicId}/${documentPublicId}/crx-stamped-${fingerprint}.${extension}`;

export const safeSegment = (value: string): string =>
  value.replace(/[^A-Za-z0-9._-]/g, '_').slice(0, 64) || 'unknown';

export interface ArtifactResult {
  key: string;
  contentType: string;
  size: number;
  sha256: string;
  kind: DeliveryKind;
  filename: string;
  cached: boolean;
}

export const deliveryFilename = (meta: DeliveryMeta, extension: string): string =>
  `CODE-Rx-${safeSegment(meta.documentReference)}-v${safeSegment(meta.version)}-client-copy.${extension}`;

export interface BucketLike {
  get(key: string): Promise<{ arrayBuffer(): Promise<ArrayBuffer> } | null>;
  put(key: string, value: Uint8Array, options?: { httpMetadata?: { contentType?: string } }): Promise<unknown>;
}

/**
 * Returns the stamped artifact for the document, rendering and caching it when
 * the cached copy is missing or stale. The cache key carries a fingerprint of
 * the source, so a changed source or version always produces a new artifact and
 * a stale one can never be served.
 */
export const ensureClientDeliveryArtifact = async (options: {
  bucket: BucketLike;
  clientPublicId: string;
  documentPublicId: string;
  input: RenderInput;
}): Promise<ArtifactResult> => {
  const { bucket, clientPublicId, documentPublicId, input } = options;
  const plan = planClientDelivery(input);
  if (!plan.available || !plan.kind) {
    throw new DeliveryRefusal(plan.reason || 'delivery_unavailable', plan.message, plan);
  }
  const fingerprint = await sourceFingerprint(input);
  const key = artifactKey(clientPublicId, documentPublicId, plan.extension, fingerprint);
  const filename = deliveryFilename(input.meta, plan.extension);

  const cached = await bucket.get(key);
  if (cached) {
    const bytes = new Uint8Array(await cached.arrayBuffer());
    if (bytes.length) {
      return {
        key,
        contentType: plan.contentType,
        size: bytes.length,
        sha256: await sha256Hex(bytes),
        kind: plan.kind,
        filename,
        cached: true,
      };
    }
  }

  const rendered = await renderClientDelivery(input);
  await bucket.put(key, rendered.bytes, { httpMetadata: { contentType: rendered.contentType } });
  return {
    key,
    contentType: rendered.contentType,
    size: rendered.bytes.length,
    sha256: rendered.sha256,
    kind: rendered.kind,
    filename,
    cached: false,
  };
};

/**
 * Re-renders and replaces the cached artifact, ignoring any cached copy. Used by
 * the Phantom "prepare client copy" action, which deliberately regenerates.
 */
export const refreshClientDeliveryArtifact = async (options: {
  bucket: BucketLike;
  clientPublicId: string;
  documentPublicId: string;
  input: RenderInput;
}): Promise<ArtifactResult> => {
  const { bucket, clientPublicId, documentPublicId, input } = options;
  const plan = planClientDelivery(input);
  if (!plan.available || !plan.kind) {
    throw new DeliveryRefusal(plan.reason || 'delivery_unavailable', plan.message, plan);
  }
  const fingerprint = await sourceFingerprint(input);
  const key = artifactKey(clientPublicId, documentPublicId, plan.extension, fingerprint);
  const rendered = await renderClientDelivery(input);
  await bucket.put(key, rendered.bytes, { httpMetadata: { contentType: rendered.contentType } });
  return {
    key,
    contentType: rendered.contentType,
    size: rendered.bytes.length,
    sha256: rendered.sha256,
    kind: rendered.kind,
    filename: deliveryFilename(input.meta, plan.extension),
    cached: false,
  };
};

/**
 * Loads the bytes of an artifact the pipeline generated. A key that is not one
 * of ours (a legacy hand-placed file, an internal `vault/...` object) is never
 * served: the caller regenerates instead.
 */
export const readClientArtifact = async (
  bucket: BucketLike,
  key: string | null,
): Promise<Uint8Array | null> => {
  if (!key || !key.startsWith(CLIENT_ARTIFACT_PREFIX)) return null;
  const object = await bucket.get(key);
  if (!object) return null;
  const bytes = new Uint8Array(await object.arrayBuffer());
  return bytes.length ? bytes : null;
};

export const isDeliveryArtifactKey = (key: string | null | undefined, clientPublicId: string, documentPublicId: string): boolean =>
  !!key && key.startsWith(`${CLIENT_ARTIFACT_PREFIX}${clientPublicId}/${documentPublicId}/crx-stamped-`);
