export interface StampedImageOptions {
  meta: DeliveryMeta;
  image: DecodedImage;
  logo?: DecodedImage | null;
  /** Marks a page break for multi-page raster deliveries (unused at present). */
  page?: number;
  pageCount?: number;
}

/**
 * Repaints a raster source as a branded Code Rx page: header band with the mark,
 * the client-document designation, the metadata block, the artwork itself with a
 * diagonal watermark burned into the pixels, and the footer. The result is a new
 * PNG — the source pixels never leave the pipeline unmarked.
 */
export const buildStampedImage = async (options: StampedImageOptions): Promise<Uint8Array> => {
  const { meta, image, logo } = options;
  const scale = image.width >= 900 ? 3 : image.width >= 480 ? 2 : 1;
  const pad = 18 * scale;
  const gap = 10 * scale;
  const headerHeight = 78 * scale;
  const footerHeight = 62 * scale;

  const contentWidth = Math.max(image.width, 520 * scale);
  const width = contentWidth + pad * 2;
  const rows: Array<[string, string]> = [
    ['PROJECT', meta.projectName],
    ['DOCUMENT', meta.documentTitle],
    ['REFERENCE', meta.documentReference],
    ['VERSION', meta.version],
    ['CLIENT', meta.clientName],
    ['DESIGNATION', STAMP_DESIGNATION],
  ];
  const rowHeight = 20 * scale;
  const metaBlockHeight = rows.length * rowHeight + 12 * scale;

  const imageScale = Math.min(1, (width - pad * 2) / image.width);
  const drawWidth = Math.max(1, Math.round(image.width * imageScale));
  const drawHeight = Math.max(1, Math.round(image.height * imageScale));
  const height = headerHeight + gap + metaBlockHeight + gap + drawHeight + gap + footerHeight;

  const canvas = new Canvas(width, height);
  canvas.fillRect(0, 0, width, height, BRAND.white, 1);

  // --- header band ---------------------------------------------------------
  canvas.fillRect(0, 0, width, headerHeight, BRAND.greenDark, 1);
  canvas.fillRect(0, headerHeight - 3 * scale, width, 3 * scale, BRAND.green, 1);
  const markSize = 46 * scale;
  if (logo) {
    const markCanvas = Canvas.from(logo);
    canvas.drawImage(markCanvas, pad, (headerHeight - markSize) / 2, markSize / logo.width, 1);
  }
  const titleText = STAMP_HEADLINE.toUpperCase();
  const titleScale = Math.max(2, Math.min(6, Math.floor(((width - pad * 2 - markSize - gap) / (titleText.length * 6)) * 1)));
  const textX = pad + (logo ? markSize + gap : 0);
  drawPixelText(canvas, titleText, textX, Math.round(headerHeight * 0.26), titleScale, BRAND.white, 1);
  const subScale = Math.max(1, Math.floor(titleScale / 2));
  drawPixelText(canvas, STAMP_DESIGNATION, textX, Math.round(headerHeight * 0.26) + 8 * titleScale + 4, subScale, [214, 232, 224], 1);
  const issuedText = `ISSUED ${meta.issuedAt.toISOString().slice(0, 10)}`;
  const issuedWidth = issuedText.length * 6 * subScale;
  drawPixelText(canvas, issuedText, Math.max(pad, width - pad - issuedWidth), Math.round(headerHeight * 0.26), subScale, [214, 232, 224], 1);

  // --- metadata block ------------------------------------------------------
  let cursorY = headerHeight + gap;
  canvas.fillRect(pad, cursorY, width - pad * 2, metaBlockHeight, [239, 247, 243], 1);
  canvas.strokeRect(pad, cursorY, width - pad * 2, metaBlockHeight, [216, 232, 224], Math.max(1, scale), 1);
  let rowY = cursorY + 10 * scale;
  const labelScale = Math.max(1, scale);
  const valueScale = Math.max(1, scale + 1);
  const labelWidth = 22 * (5 + 1) * labelScale;
  for (const [label, value] of rows) {
    drawPixelText(canvas, label, pad + 8 * scale, rowY, labelScale, BRAND.slate, 1);
    drawPixelText(canvas, value.slice(0, Math.floor((width - pad * 2 - labelWidth - 24 * scale) / (6 * valueScale))),
      pad + 8 * scale + labelWidth, rowY, valueScale, BRAND.ink, 1);
    rowY += rowHeight;
  }
  cursorY += metaBlockHeight + gap;

  // --- artwork with the watermark burned in --------------------------------
  const artwork = new Canvas(drawWidth, drawHeight);
  artwork.drawImage(Canvas.from(image), 0, 0, 1, 1);
  const watermarkScale = Math.max(2, Math.floor(Math.min(drawWidth / 26, drawHeight / 9) / 6));
  const artCenterX = drawWidth / 2;
  const artCenterY = drawHeight / 2;
  // The rotated wordmark stays low-left; the full logo sits top-right of
  // centre, so the two never overlap.
  const textAnchorX = artCenterX - drawWidth * 0.17;
  const textAnchorY = artCenterY + drawHeight * 0.11;
  artwork.drawRotatedText('CODE RX SOCIETY', textAnchorX, textAnchorY, watermarkScale, -Math.atan2(1, 2.6), [12, 32, 24], 0.10);
  artwork.drawRotatedText(STAMP_DESIGNATION, textAnchorX, textAnchorY + (8 + 3) * watermarkScale, Math.max(1, Math.floor(watermarkScale / 3)), -Math.atan2(1, 2.6), [12, 32, 24], 0.08);
  if (logo) {
    // One full, square logo — no source padding — at the documented 10% opacity.
    const cropped = squareCropArtwork(logo);
    const markSize = Math.max(24, Math.round(Math.min(drawWidth, drawHeight) * 0.38));
    const markCenterX = drawWidth * 0.66;
    const markCenterY = drawHeight * 0.32;
    artwork.drawImage(
      Canvas.from(cropped),
      Math.round(markCenterX - markSize / 2),
      Math.round(markCenterY - markSize / 2),
      markSize / cropped.width,
      0.10,
    );
  }
  canvas.drawImage(artwork, pad, cursorY, 1, 1);
  canvas.strokeRect(pad, cursorY, drawWidth, drawHeight, [216, 232, 224], Math.max(1, scale), 1);
  cursorY += drawHeight + gap;

  // --- footer --------------------------------------------------------------
  canvas.fillRect(0, height - footerHeight, width, footerHeight, BRAND.greenDark, 1);
  canvas.fillRect(0, height - footerHeight, width, 2 * scale, BRAND.green, 1);
  const footerScale = Math.max(1, scale);
  const footerTop = height - footerHeight + 12 * scale;
  const leftFooter = `${STAMP_HEADLINE.toUpperCase()}  ·  ${STAMP_DESIGNATION}`;
  drawPixelText(canvas, leftFooter, pad, footerTop, footerScale, BRAND.white, 1);
  const pageLabel = options.pageCount && options.pageCount > 1
    ? `PAGE ${options.page ?? 1} OF ${options.pageCount}`
    : 'CLIENT COPY';
  const pageWidth = pageLabel.length * 6 * footerScale;
  drawPixelText(canvas, pageLabel, Math.max(pad, width - pad - pageWidth), footerTop, footerScale, BRAND.white, 1);
  const detail = `${meta.clientName.toUpperCase()}  ·  ${meta.projectName.toUpperCase()}`
    + `  ·  ${meta.projectReference.toUpperCase()}  ·  ${meta.documentReference.toUpperCase()}  ·  V${meta.version}`;
  drawPixelText(canvas, detail.slice(0, Math.floor((width - pad * 2) / (6 * footerScale))),
    pad, footerTop + 8 * footerScale + 4, footerScale, [198, 222, 212], 1);
  drawPixelText(canvas, STAMP_NOTE.toUpperCase(), pad, footerTop + 16 * footerScale + 6, footerScale, [178, 206, 194], 1);

  return encodePng({ width, height, rgba: canvas.rgba });
};

